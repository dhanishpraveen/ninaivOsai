"""
Pydantic schemas for Phase 5: AI-Powered Story Metadata Generation.
Validates transcript input and structured Tamil metadata output.
"""

from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


# Canonical oral history categories aligned with Tamil Heritage Preservation schema
CANONICAL_CATEGORIES = [
    "Agriculture",
    "Traditional Medicine & Practices",
    "Folk Songs & Storytelling",
    "Festivals & Rituals",
    "Traditional Crafts",
    "Food Traditions",
    "Water Conservation",
    "Local History",
    "Other",
]

# Maximum allowed transcript length (characters) to prevent denial-of-service / excessive token costs
MAX_TRANSCRIPT_LENGTH = 30000
MIN_TRANSCRIPT_LENGTH = 10


class StoryMetadataRequest(BaseModel):
    """
    Request model for AI metadata generation from a reviewed Tamil transcript.
    """
    transcript: str = Field(
        ...,
        description="Reviewed Tamil oral-history transcript text",
        min_length=MIN_TRANSCRIPT_LENGTH,
        max_length=MAX_TRANSCRIPT_LENGTH,
    )
    language: str = Field(
        default="ta",
        description="Source transcript language ISO code (default: 'ta' for Tamil)",
    )
    include_english_summary: bool = Field(
        default=True,
        description="Whether to generate an optional English summary for bilingual archival discovery",
    )

    @field_validator("transcript")
    @classmethod
    def validate_non_empty_transcript(cls, value: str) -> str:
        trimmed = value.strip()
        if not trimmed:
            raise ValueError("Transcript cannot be empty or only whitespace.")
        if len(trimmed) < MIN_TRANSCRIPT_LENGTH:
            raise ValueError(
                f"Transcript is too short ({len(trimmed)} characters). "
                f"At least {MIN_TRANSCRIPT_LENGTH} characters of oral history text are required for metadata generation."
            )
        return trimmed


class StoryMetadataResponse(BaseModel):
    """
    Structured metadata response generated from a Tamil oral history transcript.
    Strictly grounded in transcript content without hallucination.
    """
    title: str = Field(..., description="Culturally authentic story title in Tamil")
    summary: str = Field(..., description="Concise summary in Tamil (2-4 sentences)")
    keywords: List[str] = Field(
        default_factory=list,
        description="Key topic keywords extracted directly from transcript context",
    )
    category: str = Field(
        default="Other",
        description="Best-fit canonical oral history category",
    )
    tags: List[str] = Field(
        default_factory=list,
        description="Search and discovery tags in Tamil and English",
    )
    english_summary: Optional[str] = Field(
        default=None,
        description="Optional English translation/summary for bilingual discovery",
    )
    is_mock: bool = Field(
        default=False,
        description="True if generated by local test fixture mode, never mistaken for production AI output",
    )
    provider: Optional[str] = Field(
        default=None,
        description="LLM provider used (e.g. 'gemini', 'openai', 'groq', 'mock')",
    )
    model: Optional[str] = Field(
        default=None,
        description="Model name used for generation",
    )


class MetadataServiceStatusResponse(BaseModel):
    """
    Health and configuration status of the Phase 5 Story Metadata Service.
    """
    configured: bool
    provider: str
    model: str
    test_mode: bool
    has_api_key: bool
    supported_providers: List[str]
    message: str
